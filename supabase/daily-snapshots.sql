-- Yahma: daily snapshots + idle-since tracking
-- Run once in Supabase SQL Editor.
-- Idempotent: safe to re-run.

-- 1) Idle start tracking on vehicles (date when the car became non-rented)
alter table public.vehicles add column if not exists idle_since date;
create index if not exists vehicles_idle_since_idx on public.vehicles(idle_since);

-- 2) Daily fleet snapshots (one row per branch per day, plus branch='ALL' for company-wide totals)
create table if not exists public.fleet_daily_snapshots (
  id bigint generated by default as identity primary key,
  snapshot_date date not null,
  branch text not null,
  total_cars integer not null default 0 check (total_cars >= 0),
  rented_cars integer not null default 0 check (rented_cars >= 0),
  idle_cars integer not null default 0 check (idle_cars >= 0),
  available_cars integer not null default 0 check (available_cars >= 0),
  ready_cars integer not null default 0 check (ready_cars >= 0),
  occupancy_rate numeric not null default 0,
  avg_idle_days numeric,
  max_idle_days integer,
  idle_loss numeric,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint fleet_daily_snapshots_date_branch_unique unique (snapshot_date, branch)
);

create index if not exists fleet_daily_snapshots_date_idx on public.fleet_daily_snapshots(snapshot_date desc);
create index if not exists fleet_daily_snapshots_branch_idx on public.fleet_daily_snapshots(branch, snapshot_date desc);

-- Keep updated_at fresh on upsert/update
create or replace function public.yahma_snapshots_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists fleet_daily_snapshots_touch_updated_at on public.fleet_daily_snapshots;
create trigger fleet_daily_snapshots_touch_updated_at
before update on public.fleet_daily_snapshots
for each row execute function public.yahma_snapshots_touch_updated_at();

-- RLS: same branch scoping as vehicles
alter table public.fleet_daily_snapshots enable row level security;

drop policy if exists "snapshots_select_branch" on public.fleet_daily_snapshots;
create policy "snapshots_select_branch"
on public.fleet_daily_snapshots for select
to authenticated
using (public.yahma_can_access_branch(branch) or public.yahma_sees_all_branches() or public.yahma_is_admin());

drop policy if exists "snapshots_insert_branch" on public.fleet_daily_snapshots;
create policy "snapshots_insert_branch"
on public.fleet_daily_snapshots for insert
to authenticated
with check (public.yahma_can_manage_branch(branch) or (branch = 'ALL' and (public.yahma_manages_all_branches() or public.yahma_is_admin())));

drop policy if exists "snapshots_update_branch" on public.fleet_daily_snapshots;
create policy "snapshots_update_branch"
on public.fleet_daily_snapshots for update
to authenticated
using (public.yahma_can_manage_branch(branch) or (branch = 'ALL' and (public.yahma_manages_all_branches() or public.yahma_is_admin())))
with check (public.yahma_can_manage_branch(branch) or (branch = 'ALL' and (public.yahma_manages_all_branches() or public.yahma_is_admin())));

drop policy if exists "snapshots_delete_admin" on public.fleet_daily_snapshots;
create policy "snapshots_delete_admin"
on public.fleet_daily_snapshots for delete
to authenticated
using (public.yahma_is_admin());

-- Realtime: optional, lets the dashboard refresh when another device saves today's snapshot
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'fleet_daily_snapshots'
  ) then
    alter publication supabase_realtime add table public.fleet_daily_snapshots;
  end if;
end $$;
