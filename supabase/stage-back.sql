-- ============================================================
--  stage-back.sql — الرجوع للمرحلة السابقة
-- ============================================================
--  السلسلة: الفحص ← تحت الدفع ← تم الدفع ← تم التجديد
--
--  قبل ده مفيش رجوع لورا خالص: تبويبا «تم الدفع» و«تم التجديد»
--  كان فيهم زرار «حذف» بيشيل السجل بس — يعني لو اتجلّدت رخصة
  كان فيهم زرار «حذف» بيشيل السجل بس — يعني لو تجدّدت رخصة
--  ترجّعك.
--
--  المشكلة اللي الحل بيحلها: كل انتقال أمامي بيكتب على بيانات
--  السيارة — «سليم» بدل «لم يفحص» لما الدفع يتسجّل، وتاريخ الرخصة
--  الجديد لما التجديد يتسجّل. فـ «ترجع السجل» لوحده مش كافي:
--  لازم ترجع الكتابة اللي على السيارة كمان، وإلا طلعت «سليم»
--  برخصة متجددة بعد ما الطلب رجع طور.
--
--  الحل: نخزّن القيمة القديمة في عمود prev_state لحظة الانتقال
--  قدام، والرجوع يقرا منها بدل ما يخمّن.
--
--  صيغة الحفظ (دمج، مش استبدال):
--      {
--        "inspectionStatus": "لم يفحص",
--        "licenseExpiry":    "2024-05-03",
--        "licenseStatus":    "منتهي"
--      }
--  الحقول الناقصة معناها إن المرحلة دي ما غيّرتهاش.
--
--  اتنفّذ على الإنتاج بالفعل. الملف ده للتوثيق وإعادة التطبيق.
-- ============================================================


-- ------------------------------------------------------------
-- 1) العمود
-- ------------------------------------------------------------
-- jsonb مش text عشان بندمج الحقول جواه من الـJS
-- (Object.assign) مش بنكتبه كله من الصفر.
alter table public.inspection_payments
  add column if not exists prev_state jsonb;


-- ------------------------------------------------------------
-- 2) القيم اللي في الأعمدة دلوقتي
-- ------------------------------------------------------------
-- اتأكد إن العمود موجود ونوعه صح. لازم يرجع:
--   prev_state | jsonb
select column_name, data_type
from information_schema.columns
where table_schema = 'public'
  and table_name   = 'inspection_payments'
  and column_name  = 'prev_state';


