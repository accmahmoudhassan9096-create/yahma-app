create index if not exists vehicles_branch_idx on public.vehicles(branch);
create index if not exists vehicles_plate_idx on public.vehicles(plate);

-- keep updated_at fresh on every write (rowToCar reads it back)
create or replace function public.yahma_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists vehicles_touch_updated_at on public.vehicles;
create trigger vehicles_touch_updated_at
before update on public.vehicles
for each row execute function public.yahma_touch_updated_at();

-- ============================================================
-- 0.1) Auto-create a profile row for every new auth user
-- Needed for Google OAuth sign-ins (which never go through the
-- admin-create-user edge function), so the account still shows up
-- in "إدارة المستخدمين" instead of being invisible until an admin
-- guesses the id and inserts it by hand.
-- ============================================================
create or replace function public.yahma_handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name', new.email), 'view')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.yahma_handle_new_user();

