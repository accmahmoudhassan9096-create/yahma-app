create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  user_email text,
  role text,
  action text not null,
  detail text,
  created_at timestamptz not null default now()
);

alter table public.audit_logs enable row level security;

-- سياسة الإدراج: مسموح للمستخدم المسجّل فقط يسجّل بخصوصه.
-- + دالة trigger تفرض الحقول الحساسة (user_id / user_email / role / created_at)
--   من مصادر موثوقة (الجلسة + جدول profiles) بدل القيم اللي يبعتها المتصفح.
drop policy if exists "audit_insert_authenticated" on public.audit_logs;
create policy "audit_insert_authenticated"
on public.audit_logs for insert
to authenticated
with check (user_id = auth.uid());

drop function if exists public.yahma_audit_logs_normalize() cascade;
create or replace function public.yahma_audit_logs_normalize()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.user_id := auth.uid();
  new.user_email := coalesce(auth.jwt() ->> 'email', new.user_email);
  select p.role into new.role from public.profiles p where p.id = auth.uid();
  if new.role is null then
    new.role := 'view';
  end if;
  new.created_at := now();
  return new;
end;
$$;

drop trigger if exists audit_logs_normalize on public.audit_logs;
create trigger audit_logs_normalize
before insert on public.audit_logs
for each row execute function public.yahma_audit_logs_normalize();

drop policy if exists "audit_select_admin" on public.audit_logs;
create policy "audit_select_admin"
on public.audit_logs for select
to authenticated
using (public.yahma_is_admin());

create index if not exists audit_logs_created_at_idx on public.audit_logs(created_at desc);

-- Server-side email schedule (times are interpreted in Asia/Riyadh).
create table if not exists public.email_schedule (
  id integer primary key check (id = 1),
  enabled boolean not null default false,
  daily_time time not null default '07:00',
  weekly_day integer not null default 0 check (weekly_day between 0 and 6),
  weekly_time time not null default '08:00',
  last_daily_date date,
  last_weekly_date date,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);

alter table public.email_schedule enable row level security;
grant select, insert, update on public.email_schedule to authenticated;
drop policy if exists "email_schedule_admin_read" on public.email_schedule;
create policy "email_schedule_admin_read" on public.email_schedule
  for select to authenticated using (public.yahma_is_admin());
drop policy if exists "email_schedule_admin_write" on public.email_schedule;
create policy "email_schedule_admin_write" on public.email_schedule
  for all to authenticated using (public.yahma_is_admin())
  with check (public.yahma_is_admin());

